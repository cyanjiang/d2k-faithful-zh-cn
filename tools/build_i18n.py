#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build / refresh a d2k-faithful language pack.

The first-run setup hash-checks all 1.06 game files, so text.uib is read-only.
This tool reads it and writes an EXTERNAL strings.tsv keyed by the original
English text, then generates a CKF bitmap font covering the translations.

    # full draft from your own game data (fill in the empty cells afterwards)
    python tools/build_i18n.py --uib "C:/DUNE2000/Data/UI_DATA/TEXT.UIB"

    # just rebuild the font after editing strings.tsv
    python tools/build_i18n.py

    # verify an existing pack
    python tools/build_i18n.py --check
"""

import argparse
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent


def parse_uib(path):
    data = Path(path).read_bytes()
    if len(data) < 4:
        raise SystemExit("TEXT.UIB too short")
    count = struct.unpack_from("<I", data, 0)[0]
    off = 4
    out = []

    def counted():
        nonlocal off
        if off + 2 > len(data):
            raise SystemExit("truncated TEXT.UIB")
        n = struct.unpack_from("<H", data, off)[0]
        off += 2
        if n < 1 or off + n > len(data):
            raise SystemExit("bad counted string length in TEXT.UIB")
        raw = data[off:off + n]
        off += n
        return raw.rstrip(b"\x00").decode("latin-1")

    for _ in range(count):
        key = counted()
        value = counted()
        out.append((key, value))
    if off != len(data):
        print(f"warning: {len(data) - off} trailing bytes in TEXT.UIB", file=sys.stderr)
    return out


def read_seed(path):
    seed = {}
    folded = {}
    if not Path(path).is_file():
        return seed, folded
    for line in Path(path).read_text(encoding="utf-8-sig").splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t", 1)
        if len(parts) != 2 or not parts[1]:
            continue
        k, v = parts[0], parts[1]
        seed[k] = v
        folded[k.strip().casefold()] = v
    return seed, folded


def is_resource(key, value):
    kl = key.lower()
    if kl.startswith("mve_"):
        return True
    if not value or len(value) > 48 or "_" not in value:
        return False
    return all(c.isalnum() or c in "_.-" for c in value)


def read_by_key(path):
    """Optional per-UIB-key translations (long briefings, duplicated values)."""
    out = {}
    p = Path(path)
    if not p.is_file():
        return out
    for line in p.read_text(encoding="utf-8-sig").splitlines():
        if not line or line.startswith("#") or "\t" not in line:
            continue
        k, v = line.split("\t", 1)
        if v.strip():
            out[k] = v
    return out


def escape_key(value):
    """Left column: keep the TSV plain ASCII while matching UIB bytes exactly.

    0xAC is the game's forced line break ("\\n"); any other high byte (cp1252
    punctuation, accented letters) is written as "\\xHH". Translation::load()
    restores both, so the key equals what StringTable::get() returns.
    """
    out = []
    for ch in value:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append(" ")
        elif ch == "\n" or code == 0xAC:
            out.append("\\n")
        elif code > 127:
            out.append(f"\\x{code:02x}")
        else:
            out.append(ch)
    return "".join(out)


def build_draft(uib, seed_paths, out_path, by_key_path):
    seed = {}
    folded = {}
    for sp in seed_paths:
        s, f = read_seed(sp)
        for k, v in s.items():
            seed.setdefault(k, v)
        for k, v in f.items():
            folded.setdefault(k, v)
    by_key = read_by_key(by_key_path)
    entries = parse_uib(uib)

    # One English value can appear under several keys. Pick the first non-empty
    # translation across all of them, preferring explicit per-key translations.
    best = {}
    for key, value in entries:
        if is_resource(key, value):
            continue
        cand = by_key.get(key) or seed.get(value) or folded.get(value.strip().casefold(), "")
        if cand and not best.get(value):
            best[value] = cand

    lines = [
        "# Generated by tools/build_i18n.py from your own TEXT.UIB.",
        "# Fill the empty cells with Chinese; empty = keep the English text.",
        "# \"\\n\" is a forced line break (the original 0xAC byte), on BOTH sides.",
        "# <exact English source>TAB<UTF-8 translation>",
    ]
    seen = set()
    translated = 0
    for key, value in entries:
        if value in seen or is_resource(key, value):
            continue
        seen.add(value)
        tr = best.get(value, "")
        if tr:
            translated += 1
        lines.append(f"{escape_key(value)}\t{tr}")
    # Seed entries that are not in this UIB still matter: a few displayed
    # strings are hardcoded in the reimplementation rather than in text.uib.
    extra = 0
    for src, tr in seed.items():
        if src not in seen and tr and "\t" not in src and "\n" not in src:
            lines.append(f"{escape_key(src)}\t{tr}")
            seen.add(src)
            extra += 1
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    Path(out_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"UIB entries: {len(entries)}, unique display strings: {len(seen)}, "
          f"translated: {translated + extra}, untranslated: {len(seen) - translated - extra}, "
          f"seed-only extras: {extra}")
    print(f"draft -> {out_path}  (edit the empty cells to add translations)")


def read_ckf(path):
    b = Path(path).read_bytes()
    if b[:8] != b"D2KCKF1\0":
        raise SystemExit(f"bad CKF magic: {path}")
    cw, ch, baseline, _ = struct.unpack_from("<HHHH", b, 8)
    count = struct.unpack_from("<I", b, 16)[0]
    off = 20
    cell = cw * ch
    if len(b) != off + count * (6 + cell):
        raise SystemExit(f"CKF size mismatch: {path}")
    cps = set()
    for _ in range(count):
        cp, adv = struct.unpack_from("<IH", b, off)
        cps.add(cp)
        off += 6 + cell
    return cps


def verify(tsv, ckf):
    chars = set()
    rows = 0
    for line in Path(tsv).read_text(encoding="utf-8-sig").splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t", 1)
        if len(parts) != 2 or not parts[1]:
            continue
        rows += 1
        for c in parts[1].replace("\\n", "").replace("\\\\", ""):
            if ord(c) > 127:
                chars.add(ord(c))
    have = read_ckf(ckf)
    missing = sorted(chars - have)
    if missing:
        print("MISSING GLYPHS: " + "".join(chr(c) for c in missing), file=sys.stderr)
        return 1
    print(f"OK: {rows} translated strings, {len(chars)} distinct non-ASCII chars, "
          f"all present in {ckf} ({len(have)} glyphs)")
    return 0


def main():
    ap = argparse.ArgumentParser(description="Build/refresh a d2k-faithful i18n pack")
    ap.add_argument("--uib", default=None, help="path to your own Data/UI_DATA/TEXT.UIB")
    ap.add_argument("--seed", default=str(ROOT / "i18n/zh-cn/strings.tsv"))
    ap.add_argument("--out", default=str(ROOT / "i18n/zh-cn/strings.tsv"))
    ap.add_argument("--ckf", default=str(ROOT / "i18n/zh-cn/font.ckf"))
    ap.add_argument("--font", default=None)
    ap.add_argument("--weight", default=None, help="named variation for variable fonts (e.g. Medium)")
    ap.add_argument("--check", action="store_true", help="only verify the pack")
    args = ap.parse_args()

    tsv = Path(args.out)
    ckf = Path(args.ckf)
    if args.check:
        return verify(tsv, ckf)

    if args.uib:
        if Path(args.seed).resolve() == tsv.resolve():
            seed_copy = ROOT / "i18n/zh-cn/seed.tsv"
            if not seed_copy.is_file():
                import shutil
                shutil.copyfile(args.seed, seed_copy)
            print(f"seed preserved at {seed_copy}")
            args.seed = str(seed_copy)
        build_draft(args.uib,
                    [args.seed, ROOT / "i18n/zh-cn/extra.tsv"],
                    tsv, ROOT / "i18n/zh-cn/by_key.tsv")

    import subprocess
    cmd = [sys.executable, str(HERE / "make_cjk_font.py"), "--strings", str(tsv),
           "--out", str(ckf)]
    if args.font:
        cmd += ["--font", args.font]
    if args.weight:
        cmd += ["--weight", args.weight]
    r = subprocess.run(cmd, cwd=str(ROOT))
    if r.returncode != 0:
        return r.returncode
    return verify(tsv, ckf)


if __name__ == "__main__":
    sys.exit(main())
